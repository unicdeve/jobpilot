package main

import (
	"fmt"
	"sort"
	"strings"
)

// component is one piece of third-party software a release ships.
type component struct {
	Group   string
	Name    string
	Version string
	// License is the license the component declares, where its package
	// manager records one.
	License string
	// URL is where its source is published, which the MPL in particular
	// asks a recipient to be told.
	URL   string
	Texts []text
}

// text is one file of a component's license or notices.
type text struct {
	Name string `json:"file"`
	Body string `json:"text"`
}

// The groups the notices list components in, in this order, each with
// what ships them.
const (
	groupGoStd      = "Go's standard library and runtime, in the daemon and the CLI"
	groupGoModules  = "Go modules, in the daemon and the CLI"
	groupPDFium     = "PDFium, compiled to WebAssembly inside the go-pdfium module, in the daemon"
	groupRustStd    = "Rust's standard library, in the desktop app"
	groupRustCrates = "Rust crates, in the desktop app"
	groupNPM        = "npm packages, in the desktop app's window"
)

var groupOrder = []string{groupGoStd, groupGoModules, groupPDFium, groupRustStd, groupRustCrates, groupNPM}

const rule = "================================================================================"

// render writes the notices: every component with where its source is,
// then every license text once, with the components it applies to. Many
// components ship word-for-word the same text, most of all Apache-2.0's,
// which is printed once rather than once for each.
func render(components []component) string {
	byGroup := map[string][]component{}
	for _, c := range components {
		byGroup[c.Group] = append(byGroup[c.Group], c)
	}

	// Each distinct text gets a number, in the order the components that
	// use it are first listed. Texts are the same when their words are,
	// however each copy is indented or wrapped, and the first copy found
	// is the one printed.
	numbers := map[string]int{}
	var bodies []string
	users := map[int][]string{}
	for _, group := range groupOrder {
		list := byGroup[group]
		sort.Slice(list, func(i, j int) bool {
			if list[i].Name != list[j].Name {
				return list[i].Name < list[j].Name
			}
			return list[i].Version < list[j].Version
		})
		for _, c := range list {
			for _, t := range c.Texts {
				key := sameWords(t.Body)
				if _, ok := numbers[key]; !ok {
					numbers[key] = len(bodies) + 1
					bodies = append(bodies, t.Body)
				}
				users[numbers[key]] = append(users[numbers[key]], c.Name+" "+c.Version+" ("+t.Name+")")
			}
		}
	}

	var b strings.Builder
	b.WriteString("THIRD-PARTY NOTICES\n\n")
	b.WriteString("JobPilot includes the third-party software below.\n")
	b.WriteString("Part 1 lists each component, where its source is published, and which of the\n")
	b.WriteString("license texts in part 2 it is distributed under. Components distributed under\n")
	b.WriteString("word-for-word the same text share one copy of it.\n\n")
	b.WriteString("This file is generated by `make notices` from what JobPilot's release builds\n")
	b.WriteString("compile in, and is not edited by hand.\n\n")
	b.WriteString(rule + "\nPART 1: COMPONENTS\n" + rule + "\n")
	for _, group := range groupOrder {
		list := byGroup[group]
		if len(list) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n%s\n\n", group)
		for _, c := range list {
			refs := make([]string, 0, len(c.Texts))
			for _, t := range c.Texts {
				refs = append(refs, fmt.Sprintf("[%d]", numbers[sameWords(t.Body)]))
			}
			fmt.Fprintf(&b, "  %s %s", c.Name, c.Version)
			if c.License != "" {
				fmt.Fprintf(&b, ", %s", c.License)
			}
			fmt.Fprintf(&b, ", license %s\n    %s\n", strings.Join(refs, " "), c.URL)
		}
	}

	b.WriteString("\n" + rule + "\nPART 2: LICENSES\n" + rule + "\n")
	for i, body := range bodies {
		fmt.Fprintf(&b, "\n[%d] The license of:\n", i+1)
		for _, user := range users[i+1] {
			fmt.Fprintf(&b, "      %s\n", user)
		}
		b.WriteString("\n")
		b.WriteString(body)
		b.WriteString("\n\n")
		b.WriteString(strings.Repeat("-", len(rule)))
		b.WriteString("\n")
	}
	return b.String()
}

// sameWords is a text with every run of whitespace made one space, which
// is the same for two copies of a license however each is laid out.
func sameWords(body string) string {
	return strings.Join(strings.Fields(body), " ")
}
