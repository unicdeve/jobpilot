package ports

import (
	"context"
)

// Request is a single generation request sent to an LLMProvider.
type Request struct {
	SystemPrompt string
	UserPrompt   string
	Temperature  float64
	MaxTokens    int
	// ResponseSchema, when set, asks the backend to constrain the model to
	// this shape (ADR-0017).
	//
	// It is a request, not a guarantee. A backend that cannot apply one
	// ignores it and returns ordinary text, which is what three of the
	// four supported backends do today — so a caller still states the
	// shape in its prompt, and still validates what comes back. The schema
	// removes a class of malformed reply; it does not remove the need to
	// check the reply means anything.
	ResponseSchema *Schema
}

// Response is the text generated by an LLMProvider for a Request, along with
// which model actually produced it.
type Response struct {
	Content string
	Model   string
}

// LLMProvider abstracts a local or remote LLM backend used for generation
// tasks such as job matching and cover letter drafting.
type LLMProvider interface {
	Generate(ctx context.Context, req Request) (Response, error)
	TestConnectivity(ctx context.Context) error
	// Provider returns a short identifier for the backend (e.g. "ollama"),
	// used to record which provider produced a given result.
	Provider() string
}
