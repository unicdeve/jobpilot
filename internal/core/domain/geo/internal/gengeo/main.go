// Command gengeo writes the geo package's generated tables from GeoNames
// (ADR-0023 §2): countries_gen.go, every country with its continent, and
// cities.tsv.gz, every city of at least minPopulation people keyed by its
// folded names.
//
// It is run by hand, through go generate in the geo package, and never at
// build or run time: the product carries the tables it was released with and
// never fetches a place name. GeoNames publishes its dumps daily without
// versions, so what pins a generation is the SHA-256 of each input, which
// the output records along with the date it was made.
//
// GeoNames is licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).
package main

import (
	"archive/zip"
	"bufio"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"time"

	"github.com/unicdev/jobpilot/internal/core/domain/geo/internal/fold"
)

const (
	citiesURL    = "https://download.geonames.org/export/dump/cities15000.zip"
	countriesURL = "https://download.geonames.org/export/dump/countryInfo.txt"

	// minPopulation is the smallest city kept. Measured against 169 stored
	// onsite locations, 100,000 places 138 of them; 15,000 places four more
	// at three times the size, and 500,000 loses Zürich.
	minPopulation = 100_000
)

// latinName is a name written in Latin script, with the punctuation place
// names use. Alternative names in other scripts cannot match text in a
// posting that JobPilot folds to Latin letters, so they are left out.
var latinName = regexp.MustCompile(`^[\p{Latin}0-9 .,'’()\-]+$`)

func main() {
	citiesPath := flag.String("cities", "", "cities15000.zip to read instead of downloading it")
	countriesPath := flag.String("countries", "", "countryInfo.txt to read instead of downloading it")
	out := flag.String("out", ".", "the geo package's directory")
	flag.Parse()

	citiesZip, err := input(*citiesPath, citiesURL)
	if err != nil {
		log.Fatal(err)
	}
	countryInfo, err := input(*countriesPath, countriesURL)
	if err != nil {
		log.Fatal(err)
	}

	countries, err := readCountries(countryInfo)
	if err != nil {
		log.Fatal(err)
	}
	cities, err := readCities(citiesZip, countries)
	if err != nil {
		log.Fatal(err)
	}

	header := fmt.Sprintf("Generated by gengeo on %s from GeoNames (CC BY 4.0).\n"+
		"countryInfo.txt sha256 %s\ncities15000.zip sha256 %s\n",
		time.Now().UTC().Format("2006-01-02"), digest(countryInfo), digest(citiesZip))

	if err := writeCountries(filepath.Join(*out, "countries_gen.go"), header, countries); err != nil {
		log.Fatal(err)
	}
	if err := writeCities(filepath.Join(*out, "cities.tsv.gz"), header, cities); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %d countries and %d city names", len(countries), len(cities))
}

func input(path, url string) ([]byte, error) {
	if path != "" {
		return os.ReadFile(path)
	}
	resp, err := http.Get(url) //nolint:gosec // a fixed GeoNames URL
	if err != nil {
		return nil, fmt.Errorf("downloading %s: %w", url, err)
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("downloading %s: status %d", url, resp.StatusCode)
	}
	return io.ReadAll(resp.Body)
}

func digest(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:])
}

type country struct {
	code, name, continent string
}

// readCountries reads countryInfo.txt: tab-separated, "#" comments, with
// the ISO code first, the name fifth and the continent ninth.
func readCountries(data []byte) (map[string]country, error) {
	countries := make(map[string]country)
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for scanner.Scan() {
		line := scanner.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Split(line, "\t")
		if len(fields) < 9 {
			return nil, fmt.Errorf("countryInfo.txt: short line %q", line)
		}
		countries[fields[0]] = country{code: fields[0], name: fields[4], continent: fields[8]}
	}
	return countries, scanner.Err()
}

// city is one name's cities: the countries it names a city of, most
// populous city first, and the English name of that city.
type city struct {
	countries  []string
	population map[string]int
	display    string
	top        int
}

// readCities reads the geoname table inside the zip: tab-separated, with
// the name second, the ASCII name third, alternative names fourth, the
// country code ninth and the population fifteenth.
//
// A name kept for several cities keeps each city's country, most populous
// first, so that "Cambridge, MA" can be told from Cambridge in England by
// what follows it (ADR-0023 §2).
func readCities(zipped []byte, countries map[string]country) (map[string]*city, error) {
	archive, err := zip.NewReader(bytes.NewReader(zipped), int64(len(zipped)))
	if err != nil {
		return nil, fmt.Errorf("reading cities15000.zip: %w", err)
	}
	if len(archive.File) == 0 {
		return nil, fmt.Errorf("cities15000.zip is empty")
	}
	file, err := archive.File[0].Open()
	if err != nil {
		return nil, err
	}
	defer func() { _ = file.Close() }()

	cities := make(map[string]*city)
	scanner := bufio.NewScanner(file)
	scanner.Buffer(make([]byte, 1<<20), 1<<24)
	for scanner.Scan() {
		fields := strings.Split(scanner.Text(), "\t")
		if len(fields) < 15 {
			continue
		}
		population, _ := strconv.Atoi(fields[14])
		code := fields[8]
		if population < minPopulation {
			continue
		}
		if _, known := countries[code]; !known {
			continue
		}
		names := append([]string{fields[1], fields[2]}, strings.Split(fields[3], ",")...)
		for _, name := range names {
			if name == "" || !latinName.MatchString(name) {
				continue
			}
			key := fold.Name(name)
			// Two letters are initials, and initials are ambiguous with
			// every country code and US state a posting abbreviates.
			if len(key) < 3 {
				continue
			}
			entry, ok := cities[key]
			if !ok {
				entry = &city{population: make(map[string]int)}
				cities[key] = entry
			}
			if population > entry.population[code] {
				entry.population[code] = population
			}
			if population > entry.top {
				entry.top, entry.display = population, fields[1]
			}
		}
	}
	for _, entry := range cities {
		for code := range entry.population {
			entry.countries = append(entry.countries, code)
		}
		sort.Slice(entry.countries, func(i, j int) bool {
			a, b := entry.countries[i], entry.countries[j]
			if entry.population[a] != entry.population[b] {
				return entry.population[a] > entry.population[b]
			}
			return a < b
		})
	}
	return cities, scanner.Err()
}

func writeCountries(path, header string, countries map[string]country) error {
	codes := make([]string, 0, len(countries))
	for code := range countries {
		codes = append(codes, code)
	}
	sort.Strings(codes)

	var b bytes.Buffer
	b.WriteString("// Code generated by gengeo. DO NOT EDIT.\n//\n")
	for _, line := range strings.Split(strings.TrimSpace(header), "\n") {
		b.WriteString("// " + line + "\n")
	}
	b.WriteString("\npackage geo\n\n// generatedCountries is every country GeoNames lists, with its continent.\n")
	b.WriteString("var generatedCountries = []Country{\n")
	for _, code := range codes {
		c := countries[code]
		fmt.Fprintf(&b, "\t{Code: %q, Name: %q, Continent: %q},\n", c.code, c.name, c.continent)
	}
	b.WriteString("}\n")

	source, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("formatting countries_gen.go: %w", err)
	}
	return os.WriteFile(path, source, 0o644)
}

// writeCities writes one "name<TAB>countries<TAB>display" line per folded
// name, the countries comma-separated, sorted so a regeneration from the
// same inputs is the same file.
func writeCities(path, header string, cities map[string]*city) error {
	names := make([]string, 0, len(cities))
	for name := range cities {
		names = append(names, name)
	}
	sort.Strings(names)

	var buf bytes.Buffer
	zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	if err != nil {
		return err
	}
	// No modification time: a regeneration differs only by its header.
	zw.ModTime = time.Time{}
	zw.Comment = strings.ReplaceAll(strings.TrimSpace(header), "\n", "; ")
	for _, name := range names {
		entry := cities[name]
		if _, err := fmt.Fprintf(zw, "%s\t%s\t%s\n", name, strings.Join(entry.countries, ","), entry.display); err != nil {
			return err
		}
	}
	if err := zw.Close(); err != nil {
		return err
	}
	return os.WriteFile(path, buf.Bytes(), 0o644)
}
